"""
ass_builder.py — Logic for generating Advanced Substation Alpha (.ass) files.
Fast and synchronous.
No subprocess, no model calls.
"""
from __future__ import annotations
from typing import List, Tuple, Optional


# Clamp boundaries for word durations.
# MIN kept tight; MAX raised to 4.0s to accommodate sustained notes in metal/ballads.
# The old 1.20s cap was cutting highlights mid-note on long vowels ("heeere!").
MIN_WORD_S = 0.03   # 3 cs
MAX_WORD_S = 4.00   # 400 cs — matches CorrectorConfig.max_word_sec_voice


def clamp_duration(dur: float,
                   min_s: float = MIN_WORD_S,
                   max_s: float = MAX_WORD_S) -> float:
    """Prende a duracao de uma palavra entre o minimo e o maximo do karaoke.

    Estava inline em to_k_tags. Extraida de volta porque tests/test_ass_builder.py
    a importa pelo nome: a importacao quebrada interrompia a COLETA da suite
    inteira, entao nenhum teste do repositorio rodava sob `pytest tests/`.
    """
    return max(min_s, min(max_s, dur))

